"""Accuracy against the hand-labelled gold set. The report is generated, never edited by hand.

    python -m src.evaluate --schema config/<schema>.yaml

Compares the model's original `value` (not the reviewed value) with gold/labels_<name>.csv.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

from .common import OUTPUT_DIR, load_records, squash
from .schema import Schema, load_schema

NOTE_FILE = OUTPUT_DIR / "weakest_field_note.md"


def same(gold, extracted) -> bool:
    """Strict match: trim, collapse whitespace, ignore case. Empty gold matches a null extraction."""
    return squash(gold) == squash(extracted)


def load_gold(path: Path) -> dict[str, dict]:
    with open(path, newline="", encoding="utf-8-sig") as handle:
        return {row["doc_id"].strip(): row for row in csv.DictReader(handle) if row.get("doc_id", "").strip()}


def compare(schema: Schema, gold: dict[str, dict], records: dict[str, dict]) -> list[dict]:
    results = []
    for doc_id in sorted(gold):
        record = records.get(doc_id)
        for name in schema.field_names:
            item = (record or {}).get("fields", {}).get(name, {})
            extracted = item.get("value") if record else None
            results.append({
                "doc_id": doc_id,
                "field": name,
                "gold": (gold[doc_id].get(name) or "").strip(),
                "extracted": extracted if record else "(not extracted)",
                "correct": bool(record) and same(gold[doc_id].get(name), extracted),
                "flagged": bool(record) and item.get("confidence", 0.0) < schema.review_threshold,
            })
    return results


def pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def render(schema: Schema, results: list[dict], records: dict[str, dict], gold_path: Path) -> str:
    doc_ids = sorted({row["doc_id"] for row in results})
    per_field = []
    for name in schema.field_names:
        rows = [row for row in results if row["field"] == name]
        per_field.append((name, sum(row["correct"] for row in rows), len(rows)))
    worst = min(per_field, key=lambda entry: entry[1] / entry[2] if entry[2] else 1)
    all_right = all(right == total for _, right, total in per_field)
    lines = [f"# Accuracy report: {schema.schema_name}", "",
             "Generated by `python -m src.evaluate`. Do not edit by hand.", "",
             "## 1. Accuracy by field", "",
             "| Field | Correct | Total | Accuracy | |", "| --- | --- | --- | --- | --- |"]
    for name, right, total in per_field:
        mark = "weakest" if (name == worst[0] and not all_right) else ""
        lines.append(f"| {name} | {right} | {total} | {pct(right, total)} | {mark} |")
    right_all, total_all = sum(e[1] for e in per_field), sum(e[2] for e in per_field)
    lines.append(f"| **overall** | {right_all} | {total_all} | {pct(right_all, total_all)} | |")
    lines += ["", f"With {len(doc_ids)} documents, one error moves a field by {pct(1, len(doc_ids))}.", "",
              "Comparison is strict: trim, collapse whitespace, ignore case; dates as YYYY-MM-DD; "
              "an empty label matches a null extraction; no fuzzy matching.", "",
              "## 2. Every mismatch", ""]
    wrong = [row for row in results if not row["correct"]]
    if wrong:
        lines += ["| doc_id | field | gold | extracted |", "| --- | --- | --- | --- |"]
        lines += [f"| {r['doc_id']} | {r['field']} | {r['gold'] or '(empty)'} | {r['extracted'] or '(null)'} |" for r in wrong]
    else:
        lines.append("None.")
    flagged = [row for row in results if row["flagged"]]
    caught = [row for row in wrong if row["flagged"]]
    lines += ["", "## 3. Review-queue catch rate", "",
              f"- Wrong fields that the review queue flagged: {len(caught)} of {len(wrong)} ({pct(len(caught), len(wrong))})",
              f"- Flagged fields that were actually wrong: {len(caught)} of {len(flagged)} ({pct(len(caught), len(flagged))})",
              f"- Review threshold: {schema.review_threshold}", ""]
    used = [records[d] for d in doc_ids if d in records]
    models = sorted({r.get("model", "unknown") for r in used}) or ["n/a"]
    last_run = max((r["extracted_at"] for r in used), default="n/a")
    lines += ["## 4. Run details", "",
              f"- Model: {', '.join(models)}", f"- Extraction run: {last_run}",
              f"- Documents: {len(doc_ids)} (gold set: `{gold_path.as_posix()}`)", ""]
    lines += ["## 5. Weakest field", ""]
    if NOTE_FILE.exists():
        lines.append(NOTE_FILE.read_text(encoding="utf-8").strip())
    else:
        lines.append(f"DRAFT - Saleh to edit. Write the note in `{NOTE_FILE.as_posix()}` and rerun.")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--schema", required=True)
    args = parser.parse_args(argv)
    schema = load_schema(args.schema)
    gold_path = Path("gold") / f"labels_{schema.label_suffix}.csv"
    records = load_records()
    results = compare(schema, load_gold(gold_path), records)
    suffix = "" if schema.label_suffix == "tender" else f"_{schema.label_suffix}"
    out = OUTPUT_DIR / f"accuracy_report{suffix}.md"
    out.write_text(render(schema, results, records, gold_path), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
